import { StrictMode } from 'react'
import { createRoot } from 'react-dom/client'
import { BrowserRouter } from 'react-router-dom'
import './index.css'
import App from './App.tsx'
import { loadOrnamentConfigs } from './ornamentConfigs'

// Config-driven ornaments register their designs before first render
// so gallery grids, pickers and ?design= deep links see them.
loadOrnamentConfigs().finally(() => {
  createRoot(document.getElementById('root')!).render(
    <StrictMode>
      <BrowserRouter>
        <App />
      </BrowserRouter>
    </StrictMode>,
  )
})
